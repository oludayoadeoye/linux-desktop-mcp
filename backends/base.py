"""Platform-neutral contract for desktop automation backends."""

from __future__ import annotations

from typing import Protocol

from mcp.server.fastmcp import Image


class DesktopBackend(Protocol):
    name: str

    def screenshot(self) -> Image: ...
    def mouse_move(self, x: int, y: int) -> str: ...
    def mouse_click(self, button: str, clicks: int) -> str: ...
    def keyboard_type(self, text: str) -> str: ...
    def keyboard_hotkey(self, keys: list[str]) -> str: ...
    def launch_application(self, application: str) -> str: ...
    def desktop_status(self) -> str: ...
    def window_list(self) -> str: ...
    def window_focus(self, match: str) -> str: ...
    def window_switch(self, direction: str) -> str: ...
    def window_minimize(self, match: str | None = None) -> str: ...
    def window_maximize(self, match: str | None = None) -> str: ...
    def window_restore(self, match: str) -> str: ...
    def window_close(self, match: str | None = None) -> str: ...
